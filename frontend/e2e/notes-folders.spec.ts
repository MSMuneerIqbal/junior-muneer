import { expect, test } from "@playwright/test";

test("folder menus rename and delete safely; Back restores the folder, filters and scroll", async ({ page, request }, info) => {
  test.setTimeout(120000);
  const api = "http://127.0.0.1:8100";
  const token = `${info.project.name}-${Date.now()}`;
  const name = `Study ${token}`;
  const renamed = `Renamed ${token}`;
  const folder = await (await request.post(`${api}/api/note-folders`, { data: { name } })).json();
  const other = await (await request.post(`${api}/api/note-folders`, { data: { name: `Other ${token}` } })).json();
  const prefix = `Class-${token}`;
  for (let n = 0; n < 12; n++) {
    const result = await request.post(`${api}/api/files`, { multipart: { folder_id: String(folder.id), file: { name: `${prefix}-${n}.txt`, mimeType: "text/plain", buffer: Buffer.from(`Original class ${n}`) } } });
    expect(result.status()).toBe(201);
  }
  const files = await (await request.get(`${api}/api/library/files?folder_id=${folder.id}`)).json();
  const date = files[0].created_at.slice(0, 10);
  await page.goto("/notes");
  await page.getByRole("button", { name: `Open folder ${name}`, exact: true }).click();
  await page.getByLabel("Search notes", { exact: true }).fill(prefix);
  await expect(page.getByLabel("Search notes", { exact: true })).toHaveValue(prefix);
  await page.getByLabel("Filter class date", { exact: true }).fill(date);
  await expect(page.getByRole("link", { name: /^Open file Class-/ })).toHaveCount(12);
  const filtered = page.url();
  const last = page.getByRole("link", { name: /^Open file Class-/ }).last();
  await last.scrollIntoViewIfNeeded();
  const scroll = await page.getByRole("region", { name: "Notes browser", exact: true }).evaluate((el) => el.scrollTop);
  await last.click();
  await expect(page.getByRole("article", { name: "Saved file", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Back to previous view", exact: true }).click();
  await expect(page).toHaveURL(filtered);
  await expect(page.getByLabel("Notes folder filter", { exact: true })).toHaveValue(String(folder.id));
  await expect(page.getByLabel("Search notes", { exact: true })).toHaveValue(prefix);
  await expect(page.getByLabel("Filter class date", { exact: true })).toHaveValue(date);
  await expect.poll(() => page.getByRole("region", { name: "Notes browser", exact: true }).evaluate((el) => el.scrollTop)).toBeGreaterThanOrEqual(Math.max(0, scroll - 10));
  await page.reload();
  await expect(page.getByRole("link", { name: /^Open file Class-/ })).toHaveCount(12);
  await page.getByRole("checkbox", { name: "Show archived notes", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Show archived notes", exact: true })).toBeChecked();
  await page.reload();
  await expect(page.getByRole("checkbox", { name: "Show archived notes", exact: true })).toBeChecked();
  await page.goBack();
  await expect(page.getByRole("checkbox", { name: "Show archived notes", exact: true })).not.toBeChecked();
  await page.getByLabel("Notes folder filter", { exact: true }).selectOption(String(other.id));
  await expect(page.getByLabel("Notes folder filter", { exact: true })).toHaveValue(String(other.id));
  await page.goBack();
  await expect(page.getByLabel("Notes folder filter", { exact: true })).toHaveValue(String(folder.id));
  await page.goForward();
  await expect(page.getByLabel("Notes folder filter", { exact: true })).toHaveValue(String(other.id));
  await page.goBack();
  await expect(page.getByLabel("Notes folder filter", { exact: true })).toHaveValue(String(folder.id));

  await page.getByRole("button", { name: `Folder options for ${name}`, exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("menu", { name: `Actions for ${name}`, exact: true })).not.toBeVisible();
  await expect(page.getByRole("button", { name: `Folder options for ${name}`, exact: true })).toBeFocused();
  await page.getByRole("button", { name: `Folder options for ${name}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Rename folder", exact: true }).click();
  const rename = page.getByRole("dialog", { name: "Rename folder", exact: true });
  await rename.getByLabel("Folder name", { exact: true }).fill(renamed);
  await rename.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(rename).not.toBeVisible();
  await expect(page.getByLabel("Notes folder filter", { exact: true })).toContainText(renamed);
  await page.getByRole("button", { name: `Folder options for ${renamed}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Delete folder", exact: true }).click();
  const confirm = page.getByRole("dialog", { name: "Delete folder", exact: true });
  await expect(confirm).toContainText("12 files");
  await expect(confirm).toContainText("Unfiled");
  await confirm.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByRole("button", { name: `Folder options for ${renamed}`, exact: true })).toBeVisible();
  await page.getByRole("button", { name: `Folder options for ${renamed}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Delete folder", exact: true }).click();
  await page.screenshot({ path: `test-results/folder-delete-${info.project.name}.png`, fullPage: true });
  await confirm.getByRole("button", { name: "Delete folder", exact: true }).click();
  await expect(page.getByLabel("Notes folder filter", { exact: true })).not.toContainText(renamed);
  const moved = await (await request.get(`${api}/api/library/files/${files[0].id}`)).json();
  expect(moved.folder_name).toBe("Unfiled");
  const original = await request.get(`${api}/api/library/files/${files[0].id}/download`);
  expect((await original.body()).toString()).toMatch(/^Original class \d+$/);
  await page.getByRole("button", { name: "Open folder Unfiled", exact: true }).click();
  await expect(page.getByRole("link", { name: /^Open file Class-/ })).toHaveCount(12);
});
