import { expect, test } from "@playwright/test";

test("learn approval, text resource editing, version preview and deleted-skill restore", async ({ page, request }, info) => {
  test.setTimeout(120_000);
  const name = `learn_${info.project.name}_${Date.now()}`;
  const label = name.replaceAll("_", " ").replace(/^./, (c) => c.toUpperCase());
  const steps = "Read my supplied class notes. List the concepts, examples and questions. Preserve the facts and date.";
  await page.goto("/");
  const box = page.getByRole("textbox", { name: "Message" });
  await box.fill(`/learn ${name} | Use when I ask for dated class notes | ${steps}`);
  await box.press("Enter");
  const card = page.getByRole("article").filter({ hasText: `Learn: ${name.replaceAll("_", " ")}` });
  await expect(card.getByTestId("approval-status")).toHaveText("Waiting for you");
  let catalog = await (await request.get("http://127.0.0.1:8100/api/skills")).json();
  expect(catalog.some((skill: { name: string }) => skill.name === name)).toBe(false);
  await card.getByRole("button", { name: "Approve & save", exact: true }).click();
  await expect(card.getByTestId("approval-status")).toHaveText("Saved");
  catalog = await (await request.get("http://127.0.0.1:8100/api/skills")).json();
  const first = catalog.find((skill: { name: string }) => skill.name === name);
  await page.goto("/settings#skills");
  const section = page.getByRole("region", { name: "Skills", exact: true });
  await section.getByRole("button", { name: `Edit ${label}`, exact: true }).click();
  await section.getByRole("button", { name: "Add resource", exact: true }).click();
  await section.getByRole("combobox", { name: "Resource 1 type", exact: true }).selectOption("script");
  await section.getByLabel("Resource 1 path", { exact: true }).fill("scripts/notes.py");
  await section.getByLabel("Resource 1 content", { exact: true }).fill("print('reviewed-script-data-only')");
  await section.getByRole("button", { name: "Save skill", exact: true }).click();
  await expect(section.getByRole("status")).toContainText("saved");
  await section.getByRole("button", { name: `Edit ${label}`, exact: true }).click();
  await expect(section.getByLabel("Resource 1 content", { exact: true })).toHaveValue("print('reviewed-script-data-only')");
  await section.getByRole("combobox", { name: "Version to review", exact: true }).selectOption(first.revision);
  await section.getByRole("button", { name: "Load selected version", exact: true }).click();
  await expect(section.getByRole("status")).toContainText("loaded for review");
  await expect(section.getByLabel("Resource 1 content", { exact: true })).toHaveCount(0);
  await expect(section.getByLabel("Instructions", { exact: true })).toHaveValue(steps);
  await section.getByRole("button", { name: "Save skill", exact: true }).click();
  await expect(section.getByRole("status")).toContainText("saved");
  await section.getByRole("button", { name: `Edit ${label}`, exact: true }).click();
  await section.getByRole("button", { name: "Delete skill", exact: true }).click();
  await section.getByRole("button", { name: "Confirm delete", exact: true }).click();
  await expect(section.getByRole("status")).toContainText("deleted");
  await section.getByText("Deleted skills", { exact: true }).click();
  await section.getByRole("button", { name: `Review restore ${label}`, exact: true }).click();
  await expect(section.getByLabel("Instructions", { exact: true })).toHaveValue(steps);
  await expect(section.getByLabel("Resource 1 content", { exact: true })).toHaveCount(0);
  await section.getByRole("button", { name: "Save skill", exact: true }).click();
  await expect(section.getByRole("status")).toContainText("saved");
});

test("skill and memory commands respond locally", async ({ page }) => {
  await page.goto("/");
  const box = page.getByRole("textbox", { name: "Message" });
  await box.fill("/skills"); await box.press("Enter");
  await expect(page.getByText(/Your skills \(edit resources and versions/)).toBeVisible();
  await box.fill("/reload-skills");
  await expect(page.getByRole("button", { name: "Send", exact: true })).toBeEnabled();
  await box.press("Enter");
  await expect(page.getByText(/Current files are loaded when a matching task needs them/)).toBeVisible();
});
